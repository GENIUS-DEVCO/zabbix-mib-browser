<?php declare(strict_types = 0);
/*
** MIB Browser module for Zabbix 8.0
** Builds a Zabbix 8.0 template (export format) from MIB objects.
**
** Approach used by official Zabbix templates:
** - scalars: SNMP agent items with get[OID.0];
** - tables: one SNMP agent master item walk[<entry OID>] (history 0), a dependent discovery rule using
**   "SNMP walk to JSON" and dependent item prototypes using "SNMP walk value".
*/

namespace Modules\MibBrowser\Lib;

class TemplateBuilder {

	public const EXPORT_VERSION = '8.0';

	private MibRepository $repository;
	private array $options;
	private array $valuemaps = [];
	private array $keys = [];
	private array $warnings = [];

	public function __construct(MibRepository $repository, array $options) {
		$this->repository = $repository;
		$this->options = $options + [
			'template' => 'Template SNMP',
			'name' => '',
			'group' => 'Templates/SNMP',
			'key_prefix' => '',
			'delay' => '1m',
			'walk_delay' => '1m',
			'lld_delay' => '1h',
			'change_per_second' => true,
			'include_scalars' => true,
			'include_tables' => true,
			'description' => ''
		];

		// Visible name keeps what the user typed; technical name only allows the characters accepted by Zabbix.
		if ($this->options['name'] === '') {
			$this->options['name'] = $this->options['template'];
		}

		$this->options['template'] = self::technicalName($this->options['template']);
	}

	/**
	 * Technical host/template name: letters, digits, spaces, dots, underscores and dashes.
	 */
	public static function technicalName(string $name): string {
		$name = preg_replace('/[^0-9A-Za-z_. -]+/', ' ', $name);
		$name = trim(preg_replace('/\s+/', ' ', $name));

		return mb_substr($name !== '' ? $name : 'Template SNMP', 0, 128);
	}

	public function getWarnings(): array {
		return $this->warnings;
	}

	/**
	 * Deterministic UUID (version 4 layout) so a re-import updates the same objects.
	 */
	public static function uuid(string ...$parts): string {
		$hash = md5(implode('|', $parts));
		$hash[12] = '4';
		$hash[16] = dechex((hexdec($hash[16]) & 0x3) | 0x8);

		return $hash;
	}

	/**
	 * Collect objects of the given roots (OIDs or "module:<NAME>").
	 *
	 * @return array  ['scalars' => [oid => node], 'rows' => [oid => node]]
	 */
	public function collect(array $roots): array {
		$nodes = [];

		foreach ($roots as $root) {
			if (strpos($root, 'module:') === 0) {
				$nodes += $this->repository->getModuleNodes(substr($root, 7));
			}
			else {
				$nodes += $this->repository->getSubtree($root);
				// A column or a table selected directly: include its row.
				$node = $this->repository->getNode($root);

				if ($node !== null && $node['kind'] === 'column') {
					$row = MibRepository::parentOid($root);
					$nodes[$row] = $this->repository->getNode($row);
				}
				elseif ($node !== null && $node['kind'] === 'table') {
					foreach ($this->repository->getSubtree($root) as $oid => $sub) {
						$nodes[$oid] = $sub;
					}
				}
			}
		}

		uksort($nodes, [MibRepository::class, 'compareOids']);

		$scalars = [];
		$rows = [];

		foreach ($nodes as $oid => $node) {
			if ($node === null) {
				continue;
			}

			if ($node['kind'] === 'scalar' && ItemMapper::isPollable($node)) {
				$scalars[(string) $oid] = $node;
			}
			elseif ($node['kind'] === 'row') {
				$readable = array_filter($this->repository->getColumns((string) $oid),
					[ItemMapper::class, 'isPollable']
				);

				if ($readable) {
					$rows[(string) $oid] = $node;
				}
			}
		}

		return ['scalars' => $scalars, 'rows' => $rows];
	}

	/**
	 * Build export array.
	 */
	public function build(array $roots, array $only_columns = []): array {
		$collected = $this->collect($roots);
		$template_name = $this->options['template'];

		$items = [];
		$discovery_rules = [];
		$mibs = [];

		if ($this->options['include_scalars']) {
			foreach ($collected['scalars'] as $oid => $node) {
				$items[] = $this->scalarItem((string) $oid, $node);
				$mibs[$node['module']] = true;
			}
		}

		if ($this->options['include_tables']) {
			foreach ($collected['rows'] as $oid => $row) {
				$columns = array_filter($this->repository->getColumns((string) $oid), [ItemMapper::class, 'isPollable']);

				if ($only_columns) {
					$columns = array_intersect_key($columns, array_flip($only_columns));
				}

				if (!$columns) {
					continue;
				}

				[$master, $rule] = $this->tableObjects((string) $oid, $row, $columns);
				$items[] = $master;
				$discovery_rules[] = $rule;
				$mibs[$row['module']] = true;
			}
		}

		if (!$items) {
			$this->warnings[] = I18n::t('No readable object (scalar or table) in the selection.');
		}

		$description = trim($this->options['description']);
		$description .= ($description !== '' ? "\n\n" : '').'MIBs: '.implode(', ', array_keys($mibs))
			."\n\nGenerated by Zabbix MIB Browser module.";

		$template = [
			'uuid' => self::uuid('template', $template_name),
			'template' => $template_name,
			'name' => $this->options['name'],
			'description' => $description,
			'groups' => [['name' => $this->options['group']]]
		];

		if ($items) {
			$template['items'] = $items;
		}

		if ($discovery_rules) {
			$template['discovery_rules'] = $discovery_rules;
		}

		if ($this->valuemaps) {
			$template['valuemaps'] = array_values($this->valuemaps);
		}

		return [
			'zabbix_export' => [
				'version' => self::EXPORT_VERSION,
				'template_groups' => [
					['uuid' => self::uuid('group', $this->options['group']), 'name' => $this->options['group']]
				],
				'templates' => [$template]
			]
		];
	}

	private function scalarItem(string $oid, array $node): array {
		$key = $this->uniqueKey(ItemMapper::key($this->options['key_prefix'], $node));
		$value_type = ItemMapper::valueType($node);

		$item = [
			'uuid' => self::uuid('item', $this->options['template'], $key),
			'name' => $node['name'],
			'type' => 'SNMP_AGENT',
			'snmp_oid' => 'get['.$oid.'.0]',
			'key' => $key,
			'delay' => $this->options['delay']
		];

		$item += $this->commonFields($node, $value_type,
			ItemMapper::preprocessing($node, (bool) $this->options['change_per_second'])
		);

		return $item;
	}

	/**
	 * Master walk item and discovery rule for a table row.
	 */
	private function tableObjects(string $row_oid, array $row, array $columns): array {
		$table_oid = MibRepository::parentOid($row_oid);
		$table = $this->repository->getNode($table_oid) ?? $row;
		$prefix = $this->options['key_prefix'];
		$master_key = $this->uniqueKey(($prefix !== '' ? rtrim($prefix, '.').'.' : '').$table['name'].'.walk');

		$master = [
			'uuid' => self::uuid('item', $this->options['template'], $master_key),
			'name' => 'SNMP walk '.$table['name'],
			'type' => 'SNMP_AGENT',
			'snmp_oid' => 'walk['.$row_oid.']',
			'key' => $master_key,
			'delay' => $this->options['walk_delay'],
			'history' => '0',
			'value_type' => 'TEXT',
			'description' => 'Master item for '.$table['module'].'::'.$table['name']
				.'. Used by discovery and item prototypes.',
			'tags' => [['tag' => 'component', 'value' => 'raw']]
		];

		// LLD macros: up to 4 label-like columns (strings, enums), at least one column.
		$macros = [];

		foreach ($columns as $col_oid => $column) {
			$is_label = ($column['base_type'] ?? '') === 'OCTET STRING'
				&& !in_array($column['syntax'] ?? '', ['PhysAddress', 'MacAddress', 'DateAndTime', 'InetAddress'], true);

			if ($is_label && count($macros) < 4) {
				$macros[(string) $col_oid] = $column;
			}
		}

		if (!$macros) {
			$first = array_key_first($columns);
			$macros[(string) $first] = $columns[$first];
		}

		$params = [];
		$label_macro = null;

		foreach ($macros as $col_oid => $column) {
			$macro = '{#'.strtoupper(preg_replace('/[^A-Za-z0-9]/', '_', $column['name'])).'}';
			$params[] = $macro;
			$params[] = (string) $col_oid;
			$params[] = ItemMapper::walkFormat($column);

			if ($label_macro === null && ($column['base_type'] ?? '') === 'OCTET STRING') {
				$label_macro = $macro;
			}
		}

		$label = $label_macro ?? '{#SNMPINDEX}';
		$prototypes = [];

		foreach ($columns as $col_oid => $column) {
			$key = $this->uniqueKey(ItemMapper::key($prefix, $column).'[{#SNMPINDEX}]');
			$value_type = ItemMapper::valueType($column);

			$steps = array_merge(
				[[
					'type' => ItemMapper::PP_SNMP_WALK_VALUE,
					'params' => $col_oid.'.{#SNMPINDEX}'."\n".ItemMapper::walkFormat($column)
				]],
				ItemMapper::preprocessing($column, (bool) $this->options['change_per_second'])
			);

			$prototype = [
				'uuid' => self::uuid('prototype', $this->options['template'], $key),
				'name' => $table['name'].' ['.$label.']: '.$column['name'],
				'type' => 'DEPENDENT',
				'key' => $key
			];

			$prototype += $this->commonFields($column, $value_type, $steps);
			$prototype['master_item'] = ['key' => $master_key];
			$prototypes[] = $prototype;
		}

		$rule_key = $this->uniqueKey(($prefix !== '' ? rtrim($prefix, '.').'.' : '').$table['name'].'.discovery');

		$rule = [
			'uuid' => self::uuid('rule', $this->options['template'], $rule_key),
			'name' => $table['name'].' discovery',
			'type' => 'DEPENDENT',
			'key' => $rule_key,
			'description' => 'Discovery of '.$table['module'].'::'.$table['name'].' rows.',
			'item_prototypes' => $prototypes,
			'master_item' => ['key' => $master_key],
			'preprocessing' => [
				['type' => 'SNMP_WALK_TO_JSON', 'parameters' => $params],
				['type' => 'DISCARD_UNCHANGED_HEARTBEAT', 'parameters' => [$this->options['lld_delay']]]
			]
		];

		return [$master, $rule];
	}

	/**
	 * Fields shared by items and prototypes: value type, units, description, preprocessing, value map, tags.
	 */
	private function commonFields(array $node, int $value_type, array $steps): array {
		$fields = [];

		if ($value_type != ItemMapper::VALUE_UINT64) {
			$fields['value_type'] = ItemMapper::VALUE_TYPE_NAMES[$value_type];
		}

		$units = ItemMapper::units($node);

		if ($units !== '') {
			$fields['units'] = $units;
		}

		$fields['description'] = ItemMapper::description($node);

		if ($steps) {
			$fields['preprocessing'] = array_map(static function(array $step): array {
				$out = ['type' => ItemMapper::PP_NAMES[$step['type']]];

				if ($step['params'] !== '') {
					$out['parameters'] = explode("\n", $step['params']);
				}

				return $out;
			}, $steps);
		}

		$valuemap = ItemMapper::valueMap($node);

		if ($valuemap !== null) {
			$name = mb_substr($valuemap['name'], 0, 64);

			if (!array_key_exists($name, $this->valuemaps)) {
				$this->valuemaps[$name] = [
					'uuid' => self::uuid('valuemap', $this->options['template'], $name),
					'name' => $name,
					'mappings' => $valuemap['mappings']
				];
			}

			$fields['valuemap'] = ['name' => $name];
		}

		$fields['tags'] = [['tag' => 'mib', 'value' => $node['module']]];

		return $fields;
	}

	private function uniqueKey(string $key): string {
		$candidate = $key;
		$n = 2;

		while (array_key_exists($candidate, $this->keys)) {
			$candidate = preg_replace('/(\[|$)/', '_'.$n.'$1', $key, 1);
			$n++;
		}

		$this->keys[$candidate] = true;

		return $candidate;
	}
}
